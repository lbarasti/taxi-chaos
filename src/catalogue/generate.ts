import { bundledArtworkPath } from './assets';
import type { ArtworkRecord, CatalogueSources, ObjectRecord, PixelCrop } from './schema';

export type InlineEntry = Readonly<{ id: string; png: string }>;

/** Every referenced image, in authored order; the inline manifest and the measured
 * source table both follow this order, so output stays byte-stable. Legacy records
 * come first, then ordinary object records with a direct `image`. */
export function inlineEntries(records: readonly ArtworkRecord[], objects: readonly ObjectRecord[] = []): readonly InlineEntry[] {
  const entries: InlineEntry[] = records.map(({ id, png }) => ({ id, png }));
  const ids = new Set(entries.map(entry => entry.id));
  if (ids.size !== entries.length) throw new Error('Duplicate artwork ID in the legacy registry');
  for (const object of objects) {
    if (object.image === undefined) continue;
    if (ids.has(object.id)) throw new Error(`Object ${object.id}: direct image ID duplicates another artwork ID`);
    entries.push({ id: object.id, png: object.image });
    ids.add(object.id);
  }
  return entries;
}

const crop = (value: PixelCrop) => `{ x: ${value.x}, y: ${value.y}, width: ${value.width}, height: ${value.height} }`;
const source = (value: CatalogueSources[string]) => `{ width: ${value.width}, height: ${value.height}, crop: ${crop(value.crop)}${value.image ? `, image: { width: ${value.image.width}, height: ${value.image.height} }` : ''} }`;

/** Render `src/catalogue/generated.ts`: static `?inline` imports for every referenced
 * image plus the measured source pixels. No hand-registered asset list or ID union.
 * PNG masters import their display-resolution WebP derivative; vector ground tiles
 * inline as authored. */
export function renderCatalogueModule(entries: readonly InlineEntry[], sources: CatalogueSources): string {
  const measured = entries.filter(entry => sources[entry.id]);
  return [
    '// Generated by `npm run artwork:prep -- --write` from src/catalogue/content.ts; do not edit by hand.',
    '// Regenerate after adding, moving or re-exporting a referenced image.',
    '',
    ...entries.map((entry, index) => `import artwork${index} from '../assets/${bundledArtworkPath(entry.png)}?inline';`),
    "import type { ArtworkSource } from './schema';",
    '',
    '/** One inline module URL per referenced image, keyed by stable artwork ID. */',
    'export const artworkInline: Readonly<Record<string, string>> = {',
    ...entries.map((entry, index) => `  '${entry.id}': artwork${index},`),
    '};',
    '',
    '/** Measured master pixels, transparent-padding crop and bundled derivative size. */',
    'export const artworkSources: Readonly<Record<string, ArtworkSource>> = {',
    ...measured.map(entry => `  '${entry.id}': ${source(sources[entry.id]!)},`),
    '};',
    '',
  ].join('\n');
}
